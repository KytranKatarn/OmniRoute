#!/usr/bin/env python3
"""One-shot test for the skill sync job."""

import sys
import os

if os.path.exists("/app"):
    sys.path.insert(0, "/app")
    os.chdir("/app")
else:
    sys.path.insert(0, "/mnt/archie_brain/platform_v2")
    sys.path.insert(0, "/mnt/archie_brain/ai_bridge")
    os.chdir("/mnt/archie_brain/platform_v2")

from database import get_db_cursor
from services.time_utils import now_local_str
import time

# When running from host, write to host path
rules_path = "/mnt/archie_brain/.claude/rules/learned-skills.md"
# When running from container, this may be different
if not os.path.exists("/mnt/archie_brain/.claude"):
    rules_path = "/app/.claude/rules/learned-skills.md"
start = time.time()

with get_db_cursor() as (conn, cur):
    cur.execute(
        """
        SELECT DISTINCT
            SPLIT_PART(title, '/', 1) || '/' || SPLIT_PART(title, '/', 2) as repo,
            title,
            LEFT(content, 600) as preview,
            created_at
        FROM knowledge_base
        WHERE knowledge_type = 'github_file'
        AND content IS NOT NULL AND content != ''
        AND (
            title ILIKE '%%/skill%%/README%%'
            OR title ILIKE '%%/agent%%/README%%'
            OR title ILIKE '%%/plugin%%/README%%'
            OR title ILIKE '%%skill-creator%%'
            OR title ILIKE '%%prompt-engineer%%'
            OR title ILIKE '%%autonomy%%'
            OR title ILIKE '%%anti-rationalization%%'
            OR title ILIKE '%%context-engineering%%'
            OR title ILIKE '%%writing-skills%%'
        )
        ORDER BY created_at DESC
        LIMIT 100
    """
    )
    skill_files = cur.fetchall()
    print(f"Found {len(skill_files)} skill files")

    if not skill_files:
        print("No skill files found. Exiting.")
        sys.exit(0)

    repos = {}
    for row in skill_files:
        repo = row["repo"]
        if repo not in repos:
            repos[repo] = []
        repos[repo].append(
            {
                "title": row["title"],
                "preview": row["preview"],
            }
        )

    cur.execute(
        """
        SELECT
            SPLIT_PART(title, '/', 1) || '/' || SPLIT_PART(title, '/', 2) as repo,
            COUNT(*) as total_files
        FROM knowledge_base
        WHERE knowledge_type = 'github_file'
        GROUP BY repo
        ORDER BY total_files DESC
    """
    )
    repo_counts = {r["repo"]: r["total_files"] for r in cur.fetchall()}

# Build the rules file — a POINTER, not a catalog (2026-09-25, instruction-budget
# cleanup). Mirrors the same change in jobs.py:sync_learned_skills() — this script is
# a duplicate standalone copy of that generator, so both must render the short form or
# running one reverts the other. The full catalog stays intact and searchable in the
# `vault_note` this job writes to knowledge_base; nothing here is deleted.
total_repos = len(repo_counts)
total_files = sum(repo_counts.values())
total_skill_files = sum(len(v) for v in repos.values())
lines = [
    "# Learned Skills from GitHub Ingestion",
    "",
    "Auto-generated by Agent Loop Job #54 (every 6 hours). This file is a POINTER —",
    "the full per-repo / per-skill catalog is NOT restated here (it duplicated a KB",
    "vault_note this same job writes, at ~17k chars of always-loaded cost for zero",
    "extra information). Search for it instead of reading it inline.",
    f"Last sync: {now_local_str()}",
    "",
    f"**{total_repos} repos ingested · {total_files} files · {total_skill_files} flagged as skill/agent/plugin content.**",
    "",
    '**To use:** `mcp search_knowledge(query, types=["github_file"])` for a specific '
    'skill/pattern, or `mcp search_knowledge(query="Claude Learned Skills Index", '
    'types=["vault_note"])` for the full generated catalog (repo table + per-skill '
    "excerpts, identical to what this file used to inline).",
    "",
    "> ⚠️ These GitHub-ingested skills are **reference docs**, NOT loadable Claude Code "
    "skills. Claude Code only loads `.claude/skills/<name>/SKILL.md` dirs + "
    "`.claude/commands/*.md`; flat files are silently ignored (KB #272126).",
    "",
    "## Key Patterns Already Integrated",
    "",
    "- **Anti-Rationalization** — rationalization table in feedback_03-never-guess.md",
    "- **Skill Creation Workflow** — brainstorm -> template -> validate -> install",
    "- **Prompt Engineering Magic Mode** — auto-refine vague prompts silently",
    "- **Autonomous Execution (Loki Mode)** — auto-resume, kanban monitoring",
]

os.makedirs(os.path.dirname(rules_path), exist_ok=True)
with open(rules_path, "w") as f:
    f.write("\n".join(lines) + "\n")

elapsed = int((time.time() - start) * 1000)
print(f"Wrote {len(repos)} repos, {sum(len(s) for s in repos.values())} skills to {rules_path} ({elapsed}ms)")
for repo, skills in sorted(repos.items()):
    print(f"  {repo}: {len(skills)} skills")
