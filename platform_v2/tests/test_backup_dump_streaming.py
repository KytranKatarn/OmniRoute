"""#5080 — `backup_database_python` must produce a RESTORABLE dump, or no file at all.

HISTORY. This file used to assert that a hand-rolled SQL emitter was byte-identical to its
pre-#5014 in-memory ancestor. Those assertions compared two LOCAL REIMPLEMENTATIONS of the
format inside the test file — they never executed the production dumper, so they stayed green
while the real dumps were unrestorable. The dump was ultimately fixed by deleting the
hand-rolled generator and shelling out to pg_dump, which makes that entire comparison moot.

What actually needed testing, and is tested here, is the contract that failed in production:

  * the artifact is generated by pg_dump (so json/jsonb, arrays, bytea, enums and encoding are
    correct by construction rather than by a fallback that str()'d Python objects into SQL);
  * a FAILED or IMPLAUSIBLY SMALL dump leaves NO FILE BEHIND. Every incident in this module has
    the same shape — something that looks like a backup, is logged `status='success'`, and
    cannot be restored. A missing file is loud; a truncated one is not;
  * memory stays bounded, which is what the original #5014 OOM was about.

These patch subprocess.Popen, so they need no database.
"""

import gzip
import os
import sys
from unittest import mock

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))


class _FakeStream:
    """Yields payload in chunks, then EOF — mimics a pipe."""

    def __init__(self, payload=b"", chunks=None):
        self._queue = list(chunks) if chunks is not None else ([payload] if payload else [])
        self.read_calls = []
        self.closed = False

    def read(self, n=-1):
        self.read_calls.append(n)
        return self._queue.pop(0) if self._queue else b""

    def close(self):
        self.closed = True


def _fake_proc(payload=b"", rc=0, stderr=b"", chunks=None):
    p = mock.MagicMock()
    p.stdout = _FakeStream(payload, chunks)
    p.stderr = _FakeStream(stderr)
    p.wait.return_value = rc
    return p


@pytest.fixture()
def mod():
    from tools.backup_manager import _shared

    return _shared


# A payload whose GZIPPED size clears _MIN_DUMP_BYTES, so the plausibility floor is not what
# these tests are exercising. The padding is os.urandom because the floor is checked against
# the COMPRESSED artifact: repetitive filler gzips down to ~100 bytes and would trip it.
GOOD_SQL = b"-- PostgreSQL database dump\nCREATE TABLE t (id integer);\n" + os.urandom(8192)


class TestUsesPgDump:
    def test_invokes_pg_dump_with_safe_flags(self, mod, tmp_path):
        out = str(tmp_path / "database.sql")
        with mock.patch.object(mod.subprocess, "Popen", return_value=_fake_proc(GOOD_SQL)) as popen:
            mod.backup_database_python(out, compress=True)
        cmd = popen.call_args[0][0]
        assert cmd[0] == "pg_dump"
        # --format=plain keeps the artifact a real .sql.gz, which is what the restore path
        # (gunzip | psql) and every existing caller already expect.
        assert "--format=plain" in cmd
        # Restoring into a sandbox DB with different roles must not fail on ownership.
        assert "--no-owner" in cmd and "--no-privileges" in cmd

    def test_password_comes_from_env_not_argv(self, mod, tmp_path):
        """A password on argv is visible in `ps` to every process on the host."""
        with mock.patch.dict(os.environ, {"DB_PASSWORD": "s3cret"}, clear=False):
            with mock.patch.object(mod.subprocess, "Popen", return_value=_fake_proc(GOOD_SQL)) as popen:
                mod.backup_database_python(str(tmp_path / "d.sql"), compress=True)
        cmd, kwargs = popen.call_args[0][0], popen.call_args[1]
        assert not any("s3cret" in str(a) for a in cmd)
        assert kwargs["env"]["PGPASSWORD"] == "s3cret"

    def test_writes_gzipped_sql_readable_back(self, mod, tmp_path):
        out = str(tmp_path / "database.sql")
        with mock.patch.object(mod.subprocess, "Popen", return_value=_fake_proc(GOOD_SQL)):
            path = mod.backup_database_python(out, compress=True)
        assert path.endswith(".sql.gz")
        with gzip.open(path, "rb") as fh:
            assert fh.read() == GOOD_SQL


class TestNeverLeaveAnUnrestorableArtifact:
    """The core lesson of #5080 / #2366 / #5062: a plausible-looking bad file is the bug."""

    def test_nonzero_exit_raises_and_removes_the_file(self, mod, tmp_path):
        out = str(tmp_path / "database.sql")
        proc = _fake_proc(b"partial output", rc=1, stderr=b"connection refused")
        with mock.patch.object(mod.subprocess, "Popen", return_value=proc):
            with pytest.raises(RuntimeError, match="pg_dump exited 1"):
                mod.backup_database_python(out, compress=True)
        assert not os.path.exists(out + ".gz"), "a partial dump must not survive a failed run"

    def test_error_message_carries_pg_dump_stderr(self, mod, tmp_path):
        """'backup failed' with no reason is what made these take days to diagnose."""
        proc = _fake_proc(b"", rc=2, stderr=b"FATAL:  password authentication failed")
        with mock.patch.object(mod.subprocess, "Popen", return_value=proc):
            with pytest.raises(RuntimeError, match="password authentication failed"):
                mod.backup_database_python(str(tmp_path / "d.sql"), compress=True)

    def test_implausibly_small_dump_is_rejected(self, mod, tmp_path):
        """pg_dump can exit 0 having written essentially nothing; that is not a restore point."""
        out = str(tmp_path / "database.sql")
        with mock.patch.object(mod.subprocess, "Popen", return_value=_fake_proc(b"x")):
            with pytest.raises(RuntimeError, match="implausibly small"):
                mod.backup_database_python(out, compress=True)
        assert not os.path.exists(out + ".gz")

    def test_successful_dump_is_kept(self, mod, tmp_path):
        out = str(tmp_path / "database.sql")
        with mock.patch.object(mod.subprocess, "Popen", return_value=_fake_proc(GOOD_SQL)):
            path = mod.backup_database_python(out, compress=True)
        assert os.path.exists(path) and os.path.getsize(path) > 0


class TestBoundedMemory:
    """#5014's OOM was caused by holding dump CONTENT in the process."""

    def test_reads_in_bounded_chunks_never_slurps(self, mod, tmp_path):
        proc = _fake_proc(chunks=[b"a" * 2048, b"b" * 2048, GOOD_SQL])
        with mock.patch.object(mod.subprocess, "Popen", return_value=proc):
            mod.backup_database_python(str(tmp_path / "d.sql"), compress=True)
        # Every read must be size-bounded. read() / read(-1) would pull the whole dump in.
        assert proc.stdout.read_calls, "stdout was never read"
        assert all(n == mod._DUMP_CHUNK_BYTES for n in proc.stdout.read_calls)

    def test_chunk_constant_is_sane(self, mod):
        assert isinstance(mod._DUMP_CHUNK_BYTES, int)
        assert 4096 <= mod._DUMP_CHUNK_BYTES <= 64 * 1024 * 1024

    def test_min_dump_floor_is_sane(self, mod):
        assert isinstance(mod._MIN_DUMP_BYTES, int)
        assert mod._MIN_DUMP_BYTES > 0
