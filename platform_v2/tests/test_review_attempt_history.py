"""Append-only per-attempt review history — the corpus #5857 needs (#5859).

`pr_reviews` is UNIQUE on (pr_number, repo) and `mark_review_done` UPDATEs `ai_summary`
IN PLACE, so a re-review DESTROYS the previous verdict. That silently deletes the single
most valuable label in the corpus: a finding that a rebuttal proved false, because the
APPROVE that proves it overwrites the REQUEST CHANGES that was wrong.

`forge_reviews` already existed with exactly the right shape (attempt_number, raw_payload)
and ZERO rows — its only writers were two INSERTs inside POST /api/forge/webhook, an
external receiver that has never fired. This wires the REAL review path to it.
"""

import sys
from pathlib import Path
from unittest import mock

_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_ROOT))

from database import get_db_cursor  # noqa: E402
from tools.repair_bay.services import pr_review_service as prs  # noqa: E402

_PR = 99990001  # sentinel, far above any real PR number
_REPO = "KytranKatarn/archie-platform"


def _cleanup():
    with get_db_cursor(commit=True) as (conn, cur):
        cur.execute("DELETE FROM forge_reviews WHERE pr_number >= 99990000")


def _rows(pr=_PR):
    with get_db_cursor() as (conn, cur):
        cur.execute(
            "SELECT attempt_number, review_status, summary, raw_payload "
            "FROM forge_reviews WHERE pr_number=%s ORDER BY attempt_number",
            (pr,),
        )
        return [dict(r) for r in cur.fetchall()]


def setup_function():
    _cleanup()


def teardown_function():
    _cleanup()


def test_an_attempt_is_appended_not_overwritten():
    prs.record_review_attempt(_PR, "VERDICT: REQUEST CHANGES", repo=_REPO, head_sha="abc1234")
    prs.record_review_attempt(_PR, "VERDICT: APPROVE", repo=_REPO, head_sha="abc1234")
    rows = _rows()
    assert len(rows) == 2, "the second review must APPEND, never replace the first"
    assert [r["attempt_number"] for r in rows] == [1, 2]


def test_the_verdict_of_each_attempt_is_queryable():
    prs.record_review_attempt(_PR, "VERDICT: REQUEST CHANGES", repo=_REPO, head_sha="abc1234")
    prs.record_review_attempt(_PR, "VERDICT: APPROVE", repo=_REPO, head_sha="abc1234")
    assert [r["review_status"] for r in _rows()] == ["REQUEST CHANGES", "APPROVE"]


def test_a_rebuttal_flip_is_recoverable_as_a_LABELLED_PAIR():
    """THE POINT. Same head SHA + verdict flipped to APPROVE + no code change between them
    ⇒ the blocking finding was FALSE. That is ground truth, generated by normal workflow,
    with no manual labelling — and today it is thrown away."""
    prs.record_review_attempt(
        _PR, "- [WARNING] bogus — why — Evidence: +x\nVERDICT: REQUEST CHANGES", repo=_REPO, head_sha="deadbee"
    )
    prs.record_review_attempt(_PR, "VERDICT: APPROVE", repo=_REPO, head_sha="deadbee")
    rows = _rows()
    shas = {r["raw_payload"].get("head_sha") for r in rows}
    assert shas == {"deadbee"}, "both attempts must record the SHA they judged"
    assert rows[0]["review_status"] == "REQUEST CHANGES" and rows[1]["review_status"] == "APPROVE"
    assert "bogus" in (rows[0]["summary"] or ""), "the refuted finding text must survive for tuning"


def test_repo_is_captured_since_the_table_has_no_repo_column():
    prs.record_review_attempt(_PR, "VERDICT: APPROVE", repo="KytranKatarn/kytran-business-suite", head_sha="f00")
    assert _rows()[0]["raw_payload"].get("repo") == "KytranKatarn/kytran-business-suite"


def test_it_NEVER_raises_because_mark_review_done_must_not_break_on_telemetry():
    """A review that completed must never be lost because a bookkeeping INSERT failed."""
    with mock.patch.object(prs, "get_db_cursor", side_effect=RuntimeError("db down")):
        assert prs.record_review_attempt(_PR, "VERDICT: APPROVE", repo=_REPO, head_sha="x") is None


def test_mark_review_done_actually_calls_it():
    """A recorder nothing calls is the forge_reviews bug all over again — the table existed
    with the right columns and 0 rows because its only writer never fired."""
    import ast

    src = (_ROOT / "tools" / "repair_bay" / "services" / "pr_review_service.py").read_text()
    fn = next(n for n in ast.walk(ast.parse(src)) if isinstance(n, ast.FunctionDef) and n.name == "mark_review_done")
    assert "record_review_attempt(" in ast.get_source_segment(src, fn)
