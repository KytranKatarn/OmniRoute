    def _get_file_type(self, path: str) -> str:
        """Get file type from path"""
        if path.endswith(".sql"):
            return "sql"
        elif path.endswith(".sh"):
            return "shell"
        elif path.endswith(".md"):
            return "markdown"
        else:
            return "text"

    async def save_to_database(self, db_connection=None) -> bool:
        """
        Save generated files to database

        Args:
            db_connection: Optional database connection

        Returns:
            bool: True if saved successfully
        """
        if not self.generated_files:
            print("[Database Generator] ⚠️ No files to save")
            return False

        if db_connection is None and not DB_AVAILABLE:
            print("[Database Generator] ⚠️ Database not available, skipping save")
            return False

        if db_connection is None:
            db_connection = db

        try:
            with db_connection.engine.connect() as conn:
                for file_data in self.generated_files:
                    # Insert file record
                    insert_query = """
                        INSERT INTO app_builder_files
                        (project_id, file_path, content, file_type, version, is_latest, created_at)
                        VALUES (%s, %s, %s, %s, %s, %s, NOW())
                    """

                    conn.execute(
                        db_connection.text(insert_query),
                        (
                            self.project_id,
                            file_data["file_path"],
                            file_data["content"],
                            file_data["file_type"],
                            1,  # version
                            True,  # is_latest
                        ),
                    )

                conn.commit()
                print(f"[Database Generator] ✅ Saved {len(self.generated_files)} files to database")
                return True

        except Exception as e:
            print(f"[Database Generator] ❌ Failed to save to database: {e}")
            return False


