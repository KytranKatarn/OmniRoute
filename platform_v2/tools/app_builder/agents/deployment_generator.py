"""
Deployment Generator Agent
Generates deployment configurations, Docker files, CI/CD pipelines
Part of A.R.C.H.I.E. App Builder - Week 6: Deployment
"""

from typing import Dict, List, Optional, Any
from datetime import datetime, timezone
import asyncio


class DeploymentGenerator:
    """
    Generates deployment files including Docker, CI/CD, and deployment scripts
    """

    def __init__(
        self,
        project_id: int,
        project_plan: Dict,
        architecture_plan: Optional[Dict] = None,
    ):
        """
        Initialize Deployment Generator

        Args:
            project_id: Project database ID
            project_plan: Technical plan from PlannerAgent
            architecture_plan: Optional architecture details
        """
        self.project_id = project_id
        self.project_plan = project_plan
        self.architecture_plan = architecture_plan or {}
        self.generated_files = []

        # Extract project details
        self.project_name = project_plan.get("project_name", "MyApp").lower().replace(" ", "_")
        self.tech_stack = project_plan.get("tech_stack", {})
        self.database_type = self.tech_stack.get("database", "postgresql").lower()

        # Deployment settings
        self.use_docker = True
        self.use_kubernetes = False
        self.ci_cd_provider = "github"  # 'github', 'gitlab', 'jenkins'

    async def generate_deployment(
        self, docker: bool = True, ci_cd: bool = True, kubernetes: bool = False
    ) -> Dict[str, Any]:
        """
        Generate all deployment files

        Args:
            docker: Generate Docker files
            ci_cd: Generate CI/CD configurations
            kubernetes: Generate Kubernetes manifests

        Returns:
            Dictionary with generation results
        """
        deployment_files = []

        # 1. Docker files
        if docker:
            docker_files = await self._generate_docker_files()
            deployment_files.extend(docker_files)

        # 2. CI/CD configurations
        if ci_cd:
            cicd_files = await self._generate_cicd_files()
            deployment_files.extend(cicd_files)

        # 3. Environment configurations
        env_files = await self._generate_environment_files()
        deployment_files.extend(env_files)

        # 4. Deployment scripts
        script_files = await self._generate_deployment_scripts()
        deployment_files.extend(script_files)

        # 5. Nginx configuration
        nginx_files = await self._generate_nginx_config()
        deployment_files.extend(nginx_files)

        # 6. Kubernetes manifests (optional)
        if kubernetes:
            k8s_files = await self._generate_kubernetes_manifests()
            deployment_files.extend(k8s_files)

        # 7. Documentation
        doc_files = await self._generate_deployment_docs()
        deployment_files.extend(doc_files)

        self.generated_files = deployment_files

        return {
            "success": True,
            "deployment_files": deployment_files,
            "file_count": len(deployment_files),
            "docker_enabled": docker,
            "ci_cd_enabled": ci_cd,
            "kubernetes_enabled": kubernetes,
        }

    # ============================================================================
    # DOCKER FILE GENERATION
    # ============================================================================

    async def _generate_docker_files(self) -> List[Dict[str, str]]:
        """Generate Docker-related files"""
        files = []

        # 1. Backend Dockerfile
        files.append(self._generate_backend_dockerfile())

        # 2. Frontend Dockerfile
        files.append(self._generate_frontend_dockerfile())

        # 3. docker-compose.yml
        files.append(self._generate_docker_compose())

        # 4. docker-compose.prod.yml
        files.append(self._generate_docker_compose_production())

        # 5. .dockerignore files
        files.append(self._generate_backend_dockerignore())
        files.append(self._generate_frontend_dockerignore())

        return files

    def _generate_backend_dockerfile(self) -> Dict[str, str]:
        """Generate Dockerfile for Flask backend"""
        content = f"""# Backend Dockerfile for {self.project_name}
# Generated by A.R.C.H.I.E. App Builder

FROM python:3.11-slim

# Set working directory
WORKDIR /app

# Install system dependencies
RUN apt-get update && apt-get install -y \\
    gcc \\
    postgresql-client \\
    && rm -rf /var/lib/apt/lists/*

# Copy requirements first (for better caching)
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt

# Copy application code
COPY . .

# Create non-root user
RUN useradd -m -u 1000 appuser && chown -R appuser:appuser /app
USER appuser

# Expose port
EXPOSE 5000

# Health check
HEALTHCHECK --interval=30s --timeout=10s --start-period=40s --retries=3 \\
    CMD python -c "import requests; requests.get('http://localhost:5000/health')"

# Run application
CMD ["gunicorn", "--bind", "0.0.0.0:5000", "--workers", "4", "--timeout", "120", "app:app"]
"""

        return {
            "path": "backend/Dockerfile",
            "content": content,
            "description": "Backend Docker container definition",
        }

    def _generate_frontend_dockerfile(self) -> Dict[str, str]:
        """Generate Dockerfile for React frontend"""
        content = f"""# Frontend Dockerfile for {self.project_name}
# Generated by A.R.C.H.I.E. App Builder

# Build stage
FROM node:18-alpine AS builder

WORKDIR /app

# Copy package files
COPY package*.json ./
RUN npm ci --only=production

# Copy source code
COPY . .

# Build application
RUN npm run build

# Production stage
FROM nginx:alpine

# Copy built files
COPY --from=builder /app/build /usr/share/nginx/html

# Copy nginx configuration
COPY nginx.conf /etc/nginx/conf.d/default.conf

# Expose port
EXPOSE 80

# Health check
HEALTHCHECK --interval=30s --timeout=10s --start-period=10s --retries=3 \\
    CMD wget --quiet --tries=1 --spider http://localhost/health || exit 1

# Run nginx
CMD ["nginx", "-g", "daemon off;"]
"""

        return {
            "path": "frontend/Dockerfile",
            "content": content,
            "description": "Frontend Docker container definition",
        }

    def _generate_docker_compose(self) -> Dict[str, str]:
        """Generate docker-compose.yml for local development"""
        db_service = ""
        if self.database_type == "postgresql":
            db_service = f"""
  database:
    image: postgres:15-alpine
    container_name: {self.project_name}_db
    environment:
      POSTGRES_DB: {self.project_name}
      POSTGRES_USER: {self.project_name}_user
      POSTGRES_PASSWORD: dev_password
    ports:
      - "5432:5432"
    volumes:
      - postgres_data:/var/lib/postgresql/data
      - ./database/schema.sql:/docker-entrypoint-initdb.d/01_schema.sql
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U {self.project_name}_user"]
      interval: 10s
      timeout: 5s
      retries: 5
"""
        elif self.database_type == "mysql":
            db_service = f"""
  database:
    image: mysql:8.0
    container_name: {self.project_name}_db
    environment:
      MYSQL_DATABASE: {self.project_name}
      MYSQL_USER: {self.project_name}_user
      MYSQL_PASSWORD: dev_password
      MYSQL_ROOT_PASSWORD: root_password
    ports:
      - "3306:3306"
    volumes:
      - mysql_data:/var/lib/mysql
      - ./database/schema.sql:/docker-entrypoint-initdb.d/01_schema.sql
    healthcheck:
      test: ["CMD", "mysqladmin", "ping", "-h", "localhost"]
      interval: 10s
      timeout: 5s
      retries: 5
"""

        content = f"""# Docker Compose for {self.project_name}
# Generated by A.R.C.H.I.E. App Builder
# Usage: docker-compose up -d

version: '3.8'

services:
{db_service}
  backend:
    build:
      context: ./backend
      dockerfile: Dockerfile
    container_name: {self.project_name}_backend
    environment:
      FLASK_ENV: development
      DATABASE_URL: {self._get_database_url('database', 'dev_password')}
      JWT_SECRET_KEY: dev_secret_key_change_in_production
      CORS_ORIGINS: http://localhost:3000
    ports:
      - "5000:5000"
    volumes:
      - ./backend:/app
    depends_on:
      database:
        condition: service_healthy
    command: flask run --host=0.0.0.0

  frontend:
    build:
      context: ./frontend
      dockerfile: Dockerfile
      target: builder
    container_name: {self.project_name}_frontend
    environment:
      REACT_APP_API_URL: http://localhost:5000/api
    ports:
      - "3000:3000"
    volumes:
      - ./frontend:/app
      - /app/node_modules
    command: npm start

volumes:
  {self._get_volume_name()}:
    driver: local

networks:
  default:
    name: {self.project_name}_network
"""

        return {
            "path": "docker-compose.yml",
            "content": content,
            "description": "Docker Compose configuration for development",
        }

