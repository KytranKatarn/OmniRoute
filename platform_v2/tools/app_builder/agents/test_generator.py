"""
Test Generator Agent
Generates comprehensive test suites for backend and frontend code
Part of A.R.C.H.I.E. App Builder - Week 5: Testing Framework
"""

from typing import Dict, List, Optional, Any
import asyncio


class TestGenerator:
    """
    Generates test files for backend (pytest) and frontend (Jest/React Testing Library)
    """

    def __init__(
        self,
        project_id: int,
        project_plan: Dict,
        architecture_plan: Optional[Dict] = None,
    ):
        """
        Initialize Test Generator

        Args:
            project_id: Project database ID
            project_plan: Technical plan from PlannerAgent
            architecture_plan: Optional architecture details
        """
        self.project_id = project_id
        self.project_plan = project_plan
        self.architecture_plan = architecture_plan or {}
        self.generated_files = []

        # Extract project details
        self.project_name = project_plan.get("project_name", "MyApp")
        self.tech_stack = project_plan.get("tech_stack", {})
        self.database_schema = project_plan.get("database_schema", {})
        self.api_endpoints = project_plan.get("api_endpoints", [])

        # Testing frameworks
        self.backend_framework = "pytest"
        self.frontend_framework = "jest"

    async def generate_tests(self, test_backend: bool = True, test_frontend: bool = True) -> Dict[str, Any]:
        """
        Generate all test files

        Args:
            test_backend: Generate backend tests
            test_frontend: Generate frontend tests

        Returns:
            Dictionary with generation results
        """
        backend_tests = []
        frontend_tests = []

        if test_backend:
            backend_tests = await self._generate_backend_tests()

        if test_frontend:
            frontend_tests = await self._generate_frontend_tests()

        all_tests = backend_tests + frontend_tests

        return {
            "success": True,
            "test_files": all_tests,
            "file_count": len(all_tests),
            "backend_tests": len(backend_tests),
            "frontend_tests": len(frontend_tests),
            "frameworks": {
                "backend": self.backend_framework if test_backend else None,
                "frontend": self.frontend_framework if test_frontend else None,
            },
        }

    # ============================================================================
    # BACKEND TEST GENERATION (PYTEST)
    # ============================================================================

    async def _generate_backend_tests(self) -> List[Dict[str, str]]:
        """Generate all backend test files using pytest"""
        test_files = []

        # 1. Test configuration files
        test_files.append(self._generate_pytest_config())
        test_files.append(self._generate_conftest())
        test_files.append(self._generate_backend_requirements())

        # 2. Model tests (one file per model)
        tables = self.database_schema.get("tables", [])
        for table in tables:
            test_files.append(self._generate_model_test(table))

        # 3. API endpoint tests (one file per resource)
        grouped_endpoints = self._group_endpoints_by_resource()
        for resource, endpoints in grouped_endpoints.items():
            test_files.append(self._generate_api_test(resource, endpoints))

        # 4. Authentication tests
        if self._has_authentication():
            test_files.append(self._generate_auth_test())

        # 5. Integration tests
        test_files.append(self._generate_integration_test())

        self.generated_files.extend(test_files)
        return test_files

