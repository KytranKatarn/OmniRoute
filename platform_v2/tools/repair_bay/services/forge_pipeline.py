def proposal_to_branch_name(proposal: Dict) -> str:
    """Generate a clean branch name from a proposal."""
    proposal_id = proposal.get("id", 0)
    title = proposal.get("title", "fix")
    # Clean title for branch name
    clean = re.sub(r"[^a-zA-Z0-9\s-]", "", title).strip().lower()
    clean = re.sub(r"\s+", "-", clean)[:40]
    return f"archie/forge/{proposal_id}-{clean}"


def proposal_to_pr_body(proposal: Dict, sandbox_results: Dict = None) -> str:
    """Build a structured PR body from a proposal."""
    lines = [
        "## F.O.R.G.E. Automated Fix",
        "",
        f"**Proposal #{proposal.get('id')}**: {proposal.get('title', 'Untitled')}",
        "",
        "### Scan Finding",
        f"- **File**: `{proposal.get('file_path', 'unknown')}`",
        f"- **Issue Type**: {proposal.get('issue_type', 'unknown')}",
        f"- **Severity**: {proposal.get('severity', 'unknown')}",
        "",
        "### Description",
        proposal.get("description", "No description available."),
        "",
    ]

    if proposal.get("suggested_fix"):
        lines.extend(
            [
                "### Suggested Fix",
                "```",
                proposal["suggested_fix"][:2000],
                "```",
                "",
            ]
        )

    if sandbox_results:
        success = sandbox_results.get("success", False)
        lines.extend(
            [
                "### Sandbox Test Results",
                f"- **Status**: {'PASSED' if success else 'FAILED'}",
            ]
        )
        if sandbox_results.get("pass_rate"):
            lines.append(f"- **Pass Rate**: {sandbox_results['pass_rate']}%")
        if sandbox_results.get("tests_run"):
            lines.append(f"- **Tests Run**: {sandbox_results['tests_run']}")
        lines.append("")

    lines.extend(
        [
            "---",
            "*Generated by F.O.R.G.E. (Full-cycle Optimization & Regenerative GitHub Engine)*",
            "*Platform: http://192.168.1.200:3000/tools/repair-bay*",
        ]
    )

    return "\n".join(lines)


def _record_on_next_window(proposal: Dict, pr_result: Dict) -> None:
    """Append a freshly-opened PR to the next maintenance window's manifest (#5247a).

    ADVISORY ONLY. This changes nothing about who merges or when. Repair Bay's
    pipeline ENDS AT PR CREATION — there is no automated deploy step to batch —
    so the manifest is a list of fixes AWAITING A HUMAN MERGE, shown to the owner
    ahead of the window. That is the coordination that was actually asked for:
    "advise and coordinate before, and let me know before the maintenance the fix list."

    ⚠️ create_if_missing=False IS LOAD-BEARING. next_window(create_if_missing=True)
    would schedule a window whenever a self-heal PR appears, and the
    maintenance_window_driver eventually OPENS scheduled windows — and opening one
    ARMS DR SUPPRESSION. Suppressing DR because a code fix got a PR would be a
    real safety regression introduced by a reporting feature. So this only ever
    appends to a window a human already scheduled; with none scheduled it logs and
    does nothing.

    BEST-EFFORT BY CONSTRUCTION. A manifest failure must never turn a successful
    PR creation into a failure — the PR is the real work and it already exists.
    add_item() also refuses once a window has OPENED, deliberately: the owner
    approved a specific list, and silently extending it afterwards would make that
    approval meaningless. That refusal is logged, not treated as an error.
    """
    try:
        from services.maintenance_schedule_service import add_item, next_window

        from .github_service import REPO_FULL

        window = next_window(create_if_missing=False)
        if not window:
            logger.info(
                "[FORGE] PR #%s: no maintenance window scheduled — not queued "
                "(a window is never auto-created; opening one arms DR suppression).",
                pr_result.get("pr_number"),
            )
            return
        title = (proposal.get("title") or proposal.get("issue_type") or "self-heal fix")[:140]
        res = add_item(
            window["id"],
            title=f"PR #{pr_result.get('pr_number')}: {title}",
            item_type="repair_bay_pr",
            ref=str(pr_result.get("pr_number")),
            added_by="repair_bay",
            # F.O.R.G.E. self-heal PRs are always against archie-platform. Without
            # this, the item's repo is NULL and _pr_on_open_window refuses it
            # ("names no repo") — the manifest would ship with zero working
            # producers (#380 fix round 1).
            repo=REPO_FULL,
        )
        if res.get("ok") is False:
            logger.info(
                "[FORGE] PR #%s not queued on window %s: %s", pr_result.get("pr_number"), window["id"], res.get("error")
            )
        else:
            logger.info(
                "[FORGE] PR #%s queued on maintenance window %s (advisory — merge stays human)",
                pr_result.get("pr_number"),
                window["id"],
            )
    except Exception as exc:  # noqa: BLE001 - never fail a created PR over bookkeeping
        logger.warning("[FORGE] could not record PR on a maintenance window: %s", exc)


def _proposal_fix_fields(proposal: Dict) -> Dict:
    """Resolve target file + fix diff across BOTH proposal generations.

    The legacy shape used file_path/code_diff attributes; audit-pipeline rows keep
    file_path in metadata jsonb and the unified diff in code_changes — there is NO
    file_path column on improvement_proposals (information_schema, 2026-08-26).
    Attribute names win when present so any legacy caller is byte-identical.
    """
    md = proposal.get("metadata") or {}
    if isinstance(md, str):
        try:
            md = json.loads(md)
        except Exception:
            md = {}
    if not isinstance(md, dict):
        md = {}
    fp = proposal.get("file_path") or md.get("file_path") or ""
    # Scanner rows carry module-tag placeholders ([APP_CORE]/..., [AI_BRIDGE]/...)
    # that match no real path. The sandbox gate already substitutes them, but this
    # resolver fed the raw token to the patch applicator, which refused every such
    # proposal ("not found under any repo root" — measured on 11181, 2026-08-27).
    # The stored diff headers use the REAL path, so only file_path needs mapping.
    # resolve_proposal_source is the single source of truth for the substitution;
    # its display_path is mount-independent (the abs/exists check is not, so only
    # display is used here). 'skip' = synthetic non-file label, left unchanged.
    if fp:
        try:
            from services.audit_pipeline import resolve_proposal_source

            _abs, display, status = resolve_proposal_source(fp)
            if status != "skip" and display:
                fp = display
        except ImportError:
            pass  # resolver unavailable — keep the raw path (previous behavior)
    return {
        "file_path": fp,
        "code_diff": proposal.get("code_diff") or proposal.get("code_changes") or "",
        "suggested_fix": proposal.get("suggested_fix") or "",
    }


def _patched_content(file_path: str, diff_text: str) -> Optional[str]:
    """Apply a unified diff to a THROWAWAY copy of the file — never the shared tree.

    Spec 2026-08-26 principle 5: no repair path writes production files. The
    patched content rides into the push clone via push_changes(content_overrides=),
    so the live volume-mounted tree stays untouched until the PR merges and the
    hub pulls. Found by the Task-14 acceptance drive: the old path imported a
    NONEXISTENT applicator function — deploy_via_forge had zero
    callers, so the ImportError had never fired — and then misreported the
    failure as "proposal has no code_diff".
    """
    import shutil
    import subprocess
    import tempfile

    from .github_service import REPO_PATH

    # The archie_platform container does NOT mount the whole repo: platform_v2/
    # lives at /app, while /mnt/archie_brain holds ai_bridge/, scripts/ etc.
    # WITHOUT platform_v2 (measured 2026-08-26 — which also means push_changes'
    # copy-from-REPO_PATH branch could never have served a platform_v2 file from
    # this container). Resolve across both roots; content is identical either way.
    candidates = [os.path.join(REPO_PATH, file_path)]
    if file_path.startswith("platform_v2/"):
        candidates.append(os.path.join("/app", file_path[len("platform_v2/") :]))
    src = next((c for c in candidates if os.path.isfile(c)), None)
    if src is None:
        logger.warning("[FORGE] _patched_content: %s not found under any repo root", file_path)
        return None
    with tempfile.TemporaryDirectory() as td:
        dst = os.path.join(td, file_path)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
        p = subprocess.run(
            ["git", "apply", "--whitespace=nowarn", "-"],
            input=diff_text,
            text=True,
            capture_output=True,
            cwd=td,
            timeout=30,
        )
        if p.returncode != 0:
            logger.warning("[FORGE] diff does not apply to %s: %s", file_path, (p.stderr or "").strip()[:200])
            return None
        with open(dst) as fh:
            return fh.read()


def deploy_via_forge(
    proposal: Dict,
    deployment_id: int,
    sandbox_results: Dict = None,
) -> Dict:
    """Deploy a proposal via F.O.R.G.E. — create branch, push changes, open PR.

    This replaces the direct _apply_changes_to_production placeholder.

    Args:
        proposal: The improvement proposal dict from DB
        deployment_id: The deployment record ID
        sandbox_results: Optional sandbox test results

    Returns:
        {
            'success': True,
            'pr_url': 'https://github.com/...',
            'pr_number': 123,
            'branch': 'archie/forge/456-fix-auth-bug',
            'method': 'forge_pr'
        }
    """
    from .github_service import (
        create_branch,
        push_changes,
        create_pr,
        health_check,
    )

    # 1. Verify GitHub access
    gh_health = health_check()
    if not gh_health.get("success"):
        return {
            "success": False,
            "error": f"GitHub not accessible: {gh_health.get('error')}",
            "fallback": "direct_apply",
        }

    # 2. Create branch
    branch_name = proposal_to_branch_name(proposal)
    branch_result = create_branch(branch_name)
    if not branch_result.get("success"):
        return {
            "success": False,
            "error": f"Branch creation failed: {branch_result.get('error')}",
        }

    # 3. Apply changes to branch — resolve across BOTH proposal shapes (spec
    # 2026-08-26 §6.2: audit-pipeline rows carry file_path in metadata and the
    # diff in code_changes; the old direct reads refused every one of them).
    fields = _proposal_fix_fields(proposal)
    file_path = fields["file_path"]
    code_diff = fields["code_diff"]
    suggested_fix = fields["suggested_fix"]

    if not file_path:
        return {
            "success": False,
            "error": "Proposal has no file_path — cannot determine which files to change",
        }

    # Apply the diff to a THROWAWAY copy; the patched content rides into the push
    # clone via content_overrides. The shared tree is never written (principle 5).
    files_changed = []
    content_overrides = {}
    if code_diff:
        patched = _patched_content(file_path, code_diff)
        if patched is not None:
            content_overrides[file_path] = patched
            files_changed = [file_path]

    # Legacy escape hatch: suggested_fix means content was pre-written into the
    # tree by an older caller — stage the file as-is from REPO_PATH.
    if not files_changed and suggested_fix:
        files_changed = [file_path]

    if not files_changed:
        # Honest error: distinguish "no diff stored" from "diff no longer applies"
        # — the old message blamed the proposal when the applicator was broken.
        if code_diff:
            return {
                "success": False,
                "error": f"fix diff no longer applies cleanly to {file_path} (file drifted since fix-gen)",
            }
        return {
            "success": False,
            "error": "No code changes to push — proposal has no code_diff or suggested_fix",
        }

    # 4. Commit and push
    commit_msg = (
        f"fix(forge): {proposal.get('title', 'automated fix')}\n\n"
        f"Proposal #{proposal.get('id')} | Deployment #{deployment_id}\n"
        f"File: {file_path}\n"
        f"Issue: {proposal.get('issue_type', 'unknown')} ({proposal.get('severity', 'unknown')})\n\n"
        f"Generated by F.O.R.G.E. — Full-cycle Optimization & Regenerative GitHub Engine"
    )
    push_result = push_changes(branch_name, files_changed, commit_msg, content_overrides=content_overrides)
    if not push_result.get("success"):
        if not push_result.get("committed", True):
            # No changes to commit — the code might already be fixed
            return {
                "success": True,
                "pr_url": None,
                "message": "No changes needed — code already matches the fix",
                "method": "no_change",
            }
        return {
            "success": False,
            "error": f"Push failed: {push_result.get('error')}",
        }

    # 5. Create PR
    pr_title = f"[FORGE] {proposal.get('title', 'Automated Fix')}"
    if len(pr_title) > 70:
        pr_title = pr_title[:67] + "..."

    pr_body = proposal_to_pr_body(proposal, sandbox_results)

    pr_result = create_pr(
        branch_name=branch_name,
        title=pr_title,
        body=pr_body,
        labels=["archie-forge", f"severity-{proposal.get('severity', 'medium')}"],
    )

    if not pr_result.get("success"):
        return {
            "success": False,
            "error": f"PR creation failed: {pr_result.get('error')}",
            "branch": branch_name,
            "pushed": True,
        }

    logger.info(
        f"[FORGE] PR #{pr_result['pr_number']} created for proposal " f"#{proposal.get('id')}: {pr_result['pr_url']}"
    )

    # #5247a — tell the owner this fix is waiting, BEFORE the window. Advisory:
    # it never merges, never schedules a window, and never fails the PR.
    _record_on_next_window(proposal, pr_result)

    return {
        "success": True,
        "pr_url": pr_result["pr_url"],
        "pr_number": pr_result["pr_number"],
        "branch": branch_name,
        "sha": push_result.get("sha"),
        "method": "forge_pr",
        "changes_applied": files_changed,
    }


def get_forge_status(proposal_id: int) -> Dict:
    """Get F.O.R.G.E. pipeline status for a proposal."""
    from .github_service import list_pipeline_prs

    result = list_pipeline_prs("all")
    if not result.get("success"):
        return {"success": False, "error": result.get("error")}

    # Find PR for this proposal
    for pr in result.get("prs", []):
        if f"#{proposal_id}" in pr.get("title", ""):
            return {
                "success": True,
                "has_pr": True,
                "pr": pr,
            }

    return {"success": True, "has_pr": False}


def deploy_via_merge(pr_number: int, proposal_id: int = None) -> Dict:
    """Deploy by merging a F.O.R.G.E. PR — with pre-merge checks.

    Verifies:
    1. PR exists and is open
    2. CodeRabbit has approved (or no reviews blocking)
    3. PR is mergeable (no conflicts)

    Then squash-merges and closes related GitHub issue.

    Args:
        pr_number: GitHub PR number
        proposal_id: Optional proposal ID to update status

    Returns:
        {'success': True, 'sha': '...', 'pr_number': 123}
    """
    from .github_service import get_pr_status, merge_pr

    # 1. Get PR status
    status = get_pr_status(pr_number)
    if not status.get("success"):
        return {"success": False, "error": f"Cannot read PR: {status.get('error')}"}

    if status.get("state") != "open":
        return {
            "success": False,
            "error": f"PR is {status.get('state')}, not open",
        }

    # 2. Check reviews
    reviews = status.get("reviews", [])
    blocking = [r for r in reviews if r.get("state") == "CHANGES_REQUESTED"]
    approved = [r for r in reviews if r.get("state") == "APPROVED"]

    if blocking:
        blockers = [r.get("user", "unknown") for r in blocking]
        return {
            "success": False,
            "error": f"Changes requested by: {', '.join(blockers)}",
            "blocking_reviews": blocking,
            "check": "review_blocked",
        }

    # 3. Check mergeable
    if status.get("mergeable") is False:
        return {
            "success": False,
            "error": "PR has merge conflicts — rebase needed",
            "check": "conflicts",
        }

    # 4. Merge
    merge_result = merge_pr(pr_number, method="squash")
    if not merge_result.get("success"):
        return {
            "success": False,
            "error": f"Merge failed: {merge_result.get('error')}",
        }

    # 4b. MERGE → AUTO-DEPLOY (deploy-provenance #5375/#2543): the hub bind-mounts
    # /mnt/archie_brain, so a merged PR is not live until the HOST fast-forwards the
    # checkout and restarts the containers. Enqueue the signed hub_deploy command
    # async (NEVER submit_and_wait — the host restarts archie_platform, the container
    # we run inside, so waiting would kill this request mid-reply).
    deploy_info = {"enqueued": False}
    try:
        from tools.system_operations.host_command_client import submit_host_command

        command_id = submit_host_command(
            "hub_deploy",
            {},
            submitted_by="forge_deploy",
        )
        deploy_info = {"enqueued": True, "command_id": command_id, "command_type": "hub_deploy"}
        logger.info("[FORGE] deploy_via_merge: PR #%s merged — hub_deploy enqueued (%s)", pr_number, command_id)
    except Exception as deploy_exc:
        logger.warning("[FORGE] deploy_via_merge: PR #%s merged but hub_deploy not enqueued: %s", pr_number, deploy_exc)
        deploy_info = {"enqueued": False, "error": str(deploy_exc)}

    # 5. Update proposal status if provided
    if proposal_id:
        try:
            import psycopg2

            conn = psycopg2.connect(
                host=os.getenv("DB_HOST", "archie_database"),
                database=os.getenv("DB_NAME", "archie"),
                user=os.getenv("DB_USER", "archie"),
                password=_get_db_password(),
            )
            cur = conn.cursor()
            try:
                cur.execute(
                    """UPDATE improvement_proposals
                       SET status = 'deployed'
                       WHERE id = %s""",
                    (proposal_id,),
                )
                cur.execute(
                    """UPDATE improvement_deployments
                       SET status = 'deployed', completed_at = NOW()
                       WHERE proposal_id = %s AND status = 'deploying'""",
                    (proposal_id,),
                )
                conn.commit()

                # Bridge to Code Health: mark affected module audit as stale
                cur2 = conn.cursor()
                try:
                    # #6045: there is no file_path column — it lives in metadata jsonb.
                    # The old column SELECT raised into the swallowed except below, so
                    # merged fixes never invalidated stale module audits.
                    cur2.execute(
                        "SELECT metadata->>'file_path' FROM improvement_proposals WHERE id = %s",
                        (proposal_id,),
                    )
                    prow = cur2.fetchone()
                    if prow and prow[0]:
                        parts = prow[0].split("/")
                        if "tools" in parts:
                            idx = parts.index("tools")
                            if idx + 1 < len(parts):
                                affected = parts[idx + 1]
                                from services.code_metrics_service import mark_stale_audits

                                mark_stale_audits([affected])
                                logger.info(f"[FORGE] Marked {affected} audit stale after deploy")
                                _reaudit_module(affected)
                finally:
                    cur2.close()
            finally:
                cur.close()
                conn.close()
        except Exception as db_err:
            logger.warning(f"[FORGE] DB update after merge failed: {db_err}")

    # 6. Send Telegram notification
    try:
        from services.telegram_service import send_forge

        text = (
            f"PR #{pr_number} merged successfully\n"
            f"{'Proposal #' + str(proposal_id) if proposal_id else ''}\n"
            f"Approved by: {', '.join(r.get('user', '?') for r in approved) or 'none'}\n\n"
            f"Code is now in main."
        )
        send_forge("PR Merged & Deployed", text, source_module="forge_pipeline")
    except Exception as tg_err:
        logger.warning(f"[FORGE] Telegram notification failed: {tg_err}")

    logger.info(f"[FORGE] PR #{pr_number} merged — proposal #{proposal_id} deployed")

    return {
        "success": True,
        "pr_number": pr_number,
        "proposal_id": proposal_id,
        "sha": merge_result.get("sha", ""),
        "approved_by": [r.get("user") for r in approved],
        "method": "forge_merge",
        "deploy": deploy_info,
    }


def complete_proposal_after_merge(proposal_id: int, pr_number: int) -> bool:
    """Flip a pr_open proposal to a REAL deployed state after its PR merged.

    Spec 2026-08-26 §6.4. This is the ONLY writer that sets code_applied: true —
    it fires exclusively on a confirmed GitHub merge, so 'deployed' finally means
    'merged into the tree' (gate on the artifact, ADR-014). Also completes the
    improvement_deployments row and invalidates the module's stale audit.
    """
    from database import get_db_cursor

    with get_db_cursor(commit=True) as (conn, cur):
        cur.execute(
            """UPDATE improvement_proposals
               SET status = 'deployed',
                   deployed_at = NOW(),
                   metadata = COALESCE(metadata, '{}'::jsonb) || %s::jsonb
               WHERE id = %s AND status = 'pr_open'
               RETURNING id""",
            (
                json.dumps(
                    {"code_applied": True, "merged_pr": pr_number, "merged_at": time.strftime("%Y-%m-%dT%H:%M:%S")}
                ),
                proposal_id,
            ),
        )
        flipped = cur.fetchone() is not None
        if flipped:
            cur.execute(
                """UPDATE improvement_deployments
                   SET status = 'deployed', completed_at = NOW()
                   WHERE proposal_id = %s AND status = 'deploying'""",
                (proposal_id,),
            )
    if flipped:
        # Bridge to Code Health (same derivation as deploy_via_merge's block).
        try:
            from database import get_db_cursor as _gdc

            with _gdc() as (c2, cur2):
                cur2.execute(
                    "SELECT metadata->>'file_path' AS fp FROM improvement_proposals WHERE id = %s",
                    (proposal_id,),
                )
                prow = cur2.fetchone()
            fp = prow and prow.get("fp")
            if fp:
                parts = fp.split("/")
                if "tools" in parts:
                    idx = parts.index("tools")
                    if idx + 1 < len(parts):
                        from services.code_metrics_service import mark_stale_audits

                        mark_stale_audits([parts[idx + 1]])
                        _reaudit_module(parts[idx + 1])
        except Exception as bridge_err:
            logger.warning(
                "complete_proposal_after_merge: stale-audit bridge failed for #%s: %s", proposal_id, bridge_err
            )
    return flipped


# Post-merge re-audits already run for this module within the TTL are skipped —
# a bulk approval settles several proposals for the same module in one poll
# cycle, and one fresh audit covers them all.
_REAUDIT_RECENT: Dict = {}
_REAUDIT_TTL_S = 120


def _reaudit_module(module_key):
    """Re-run the static audit for one module right after its fix merges, so the
    Code Health "Issues" count decrements within the poll cycle instead of
    holding the pre-fix number until the nightly audit-all (mark_stale_audits
    alone only flips a stale flag — the old count stays on screen, task #6107).
    Best-effort: a failed audit never blocks merge settlement."""
    import time as _time

    now = _time.time()
    if now - _REAUDIT_RECENT.get(module_key, 0) < _REAUDIT_TTL_S:
        return
    _REAUDIT_RECENT[module_key] = now
    try:
        from tools.consciousness.code_health_routes import run_code_health_audit

        payload, _status = run_code_health_audit(module_key)
        result = (payload.get("results") or [{}])[0] if payload.get("success") else {}
        logger.info("[FORGE] post-merge re-audit of %s: issues now %s", module_key, result.get("issues", "unknown"))
    except Exception:
        logger.warning("[FORGE] post-merge re-audit failed for %s", module_key, exc_info=True)


def complete_merged_fix_proposals() -> Dict:
    """Settle every pr_open proposal against GitHub.

    Called from pr_review_service.sync_closed_prs — the choke point all three PR
    pollers share (#2736 pattern), so completion cannot depend on which poller ran.

    FAIL-SAFE: pr_merge_state() None (GitHub unreadable) leaves the row ALONE —
    a blip must never complete or fail a proposal (the pr_is_open None rule).
    merged -> deployed with code_applied:true; closed-unmerged -> fix_requested.
    """
    from database import get_db_cursor

    from .github_service import pr_merge_state

    checked = completed = reopened = 0
    with get_db_cursor() as (conn, cur):
        cur.execute(
            """SELECT id, (metadata->>'pr_number')::int AS pr_number
               FROM improvement_proposals
               WHERE status = 'pr_open' AND metadata->>'pr_number' IS NOT NULL
               ORDER BY id"""
        )
        rows = [dict(r) for r in cur.fetchall()]
    for row in rows:
        checked += 1
        state = pr_merge_state(row["pr_number"])
        if state == "merged":
            if complete_proposal_after_merge(row["id"], row["pr_number"]):
                completed += 1
        elif state == "closed":
            with get_db_cursor(commit=True) as (conn, cur):
                cur.execute(
                    """UPDATE improvement_proposals
                       SET status = 'fix_requested',
                           metadata = COALESCE(metadata, '{}'::jsonb)
                                      || jsonb_build_object('pr_closed_unmerged', %s)
                       WHERE id = %s AND status = 'pr_open'""",
                    (row["pr_number"], row["id"]),
                )
            reopened += 1
        # 'open' or None: leave the row alone.
    if checked:
        logger.info("[FORGE] merged-fix sweep: checked=%s completed=%s reopened=%s", checked, completed, reopened)
    return {"checked": checked, "completed": completed, "reopened": reopened}
