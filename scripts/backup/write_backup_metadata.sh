#!/usr/bin/env bash
# scripts/backup/write_backup_metadata.sh <run_dir>
# Make a Phase 1-6 backup self-describing + self-recovering (Task #4049):
#   - metadata.json : real per-DB object/table counts (preview-restore stops under-reporting;
#                     module restore stops 400'ing on "metadata not found")
#   - rollback.sh   : the UI /restore route looks for this; it execs restore_db.sh (prod restore
#                     is destructive → guarded by DR_CONFIRM=RESTORE-NOW inside restore_db.sh)
# Counts are best-effort (0 on failure) — never fail the backup over metadata.
set -euo pipefail

RUN="${1:?run_dir required}"
DB_DIR="$RUN/database"
[[ -d "$DB_DIR" ]] || { echo "no database/ in $RUN — nothing to do"; exit 0; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
IMG="pgvector/pgvector:pg16"

# Count TOC objects + table definitions in an -Fc dump via a throwaway container that has
# pg_restore (the dump is mounted read-only; pg_restore --list reads only the header/TOC, fast).
counts() {
    docker run --rm -v "$1":/d.dump:ro "$IMG" pg_restore --list /d.dump 2>/dev/null | awk '
        /^;/ { next }
        { total++; for (i = 1; i <= NF; i++) if ($i == "TABLE") { if ($(i+1) != "DATA") tbl++; break } }
        END { printf "%d %d", total + 0, tbl + 0 }' 2>/dev/null || echo "0 0"
}

ts="$(basename "$RUN" | grep -oE '[0-9]{8}_[0-9]{6}' | head -1 || true)"

db_json=""
for f in "$DB_DIR"/*.dump; do
    [[ -e "$f" ]] || continue
    base="$(basename "$f")"
    name="${base%%_*}"                       # archie_2026...dump -> archie
    size="$(stat -c %s "$f")"
    read -r objs tbls <<<"$(counts "$f")"
    case "$name" in
        archie | wtf) cont="archie_database" ;;
        creed)        cont="creed_postgres" ;;
        *)            cont="" ;;
    esac
    [[ -n "$db_json" ]] && db_json+=","
    db_json+=$(printf '{"name":"%s","file":"database/%s","size_bytes":%s,"object_count":%s,"table_count":%s,"container":"%s"}' \
        "$name" "$base" "$size" "$objs" "$tbls" "$cont")
done

comp_json=""
for c in code gitbundles config volumes; do
    [[ -d "$RUN/$c" ]] || continue
    fc=$(find "$RUN/$c" -type f 2>/dev/null | wc -l)
    [[ -n "$comp_json" ]] && comp_json+=","
    comp_json+=$(printf '{"name":"%s","file_count":%s}' "$c" "$fc")
done

cat > "$RUN/metadata.json" <<JSON
{
  "ts": "$ts",
  "layout": "phase16",
  "created_by": "backup_triage.sh",
  "databases": [$db_json],
  "components": [$comp_json]
}
JSON

# Self-contained rollback.sh — the UI /restore/<name> route runs this. Absolute path to
# restore_db.sh (valid on the hub; DR-node recovery uses the dr/ scripts).
cat > "$RUN/rollback.sh" <<ROLLBACK
#!/usr/bin/env bash
# Auto-generated by write_backup_metadata.sh (#4049) — restore THIS backup's databases.
# Verify SAFELY (throwaway container, never touches prod):
#   "$SCRIPT_DIR/restore_db.sh" "$RUN" --db all
# PROD restore (destructive — stop archie_platform first, then):
#   DR_CONFIRM=RESTORE-NOW "$SCRIPT_DIR/restore_db.sh" "$RUN" --db all --force
exec env DR_CONFIRM="\${DR_CONFIRM:-}" "$SCRIPT_DIR/restore_db.sh" "$RUN" --db all --force
ROLLBACK
chmod +x "$RUN/rollback.sh"

echo "wrote metadata.json + rollback.sh into $RUN"
