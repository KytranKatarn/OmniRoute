#!/usr/bin/env bash
# scripts/install_backup_cron.sh
# Idempotent installer for /etc/cron.d/archie-backup.
# Must be run as root (sudo). Safe to re-run.
#
# Converts scripts/archie_crontab.txt (user-crontab format) to
# /etc/cron.d/ format (adds user column) and drops it in place with
# correct perms (root:root 0644).

set -euo pipefail

REPO="/mnt/archie_brain"
SRC="$REPO/scripts/archie_crontab.txt"
DST="/etc/cron.d/archie-backup"
USER_FOR_CRON="kytran"

[[ $EUID -eq 0 ]] || { echo "Must run as root (use sudo)."; exit 2; }
[[ -f "$SRC" ]] || { echo "Missing $SRC"; exit 1; }

# Build /etc/cron.d/ file — skip comments and blanks from source, add user column to each entry.
{
    echo "# /etc/cron.d/archie-backup"
    echo "# Generated by scripts/install_backup_cron.sh on $(date -u +%FT%TZ)"
    echo "# Source: $SRC — edit that file, re-run installer."
    echo "SHELL=/bin/bash"
    echo "PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
    echo "MAILTO=\"\""
    echo ""
    # Each non-comment, non-blank line: insert USER_FOR_CRON after minute/hour/dom/mon/dow.
    awk -v user="$USER_FOR_CRON" '
        /^#/ || NF == 0 { print; next }
        { $6 = user " " $6; print }
    ' "$SRC"
} > "$DST.tmp"

chown root:root "$DST.tmp"
chmod 0644 "$DST.tmp"
mv "$DST.tmp" "$DST"

# Tell cron to reload (most distros watch /etc/cron.d, but a restart is safer).
# Fail loudly if neither works — silent reload failure defeats idempotency.
if ! systemctl reload cron 2>/dev/null && ! systemctl restart cron; then
    echo "ERROR: systemctl reload/restart cron both failed — cron daemon may be down." >&2
    echo "Check: systemctl status cron" >&2
    exit 3
fi

echo "Installed $DST"
ls -la "$DST"
